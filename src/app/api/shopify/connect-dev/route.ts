import { NextRequest } from "next/server";
import { z } from "zod";
import { requireAuthContext } from "@/lib/auth/get-auth-context";
import { shopDomainSchema } from "@/lib/validation/shopify";
import { fetchShopInfo } from "@/services/shopify-oauth-service";
import { finalizeStoreConnection } from "@/services/shopify-connection-service";
import { ok, fail, handleApiError, ApiError } from "@/lib/utils/api-response";
import { rateLimit, getClientIp } from "@/lib/utils/rate-limit";
import { getServerEnv } from "@/lib/env";

const bodySchema = z.object({
  shop: shopDomainSchema,
  accessToken: z.string().trim().min(1, "Access token is required"),
});

/**
 * Local-development-only connection path: takes a Shopify Admin API access token generated by a
 * custom app in the merchant's own store admin (Settings -> Apps and sales channels -> Develop
 * apps), bypassing the OAuth dance entirely. This exists because OAuth's redirect_uri must share
 * a host with the Partner Dashboard's Application URL, which `localhost` cannot satisfy without a
 * tunnel. Never a substitute for the real OAuth flow in production — disabled outside development
 * so it can never become a production bypass.
 */
export async function POST(request: NextRequest) {
  try {
    const env = getServerEnv();
    if (env.NODE_ENV === "production") {
      return fail(403, "DEV_ONLY", "This connection method is disabled outside local development.");
    }

    const auth = await requireAuthContext();

    const ip = getClientIp(request);
    const limit = rateLimit(`connect-dev:${auth.userId}:${ip}`, 10, 60 * 60 * 1000);
    if (!limit.success) {
      return fail(429, "RATE_LIMITED", "Too many attempts. Please try again later.");
    }

    const { shop, accessToken } = bodySchema.parse(await request.json());

    let shopInfo: { id: string; name: string };
    try {
      shopInfo = await fetchShopInfo(shop, accessToken);
    } catch {
      throw new ApiError(
        400,
        "INVALID_ACCESS_TOKEN",
        "Could not verify this access token against the store. Check the shop domain, the token, and that it has at least read_products access."
      );
    }

    const store = await finalizeStoreConnection({
      tenantId: auth.userId,
      shopDomain: shop,
      accessToken,
      shopifyShopId: shopInfo.id,
      shopName: shopInfo.name,
      // A custom app token's granted scopes aren't returned by this call; recorded as configured
      // rather than verified — informational only, not used for any authorization decision.
      scopes: env.SHOPIFY_SCOPES.split(",").map((s) => s.trim()),
      tokenType: "custom",
    });

    return ok({ storeId: store._id.toString(), shopName: shopInfo.name });
  } catch (error) {
    return handleApiError(error);
  }
}
